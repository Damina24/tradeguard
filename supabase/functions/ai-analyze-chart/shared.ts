export const ANALYSIS_MODEL = 'gpt-4o-mini';

/** Prompts are versioned in source (TRD ┬º7). Bump when the prompt or JSON contract moves. */
export const PROMPT_VERSION = 'ai-analyze-chart-v1';

/** Output caps. A model that ignores the schema must not be able to blow up a sheet. */
export const MAX_LEVELS = 6;
export const MAX_TAKE_PROFITS = 3;
export const MAX_NOTE_CHARS = 400;

export type Bias = 'bullish' | 'bearish' | 'neutral';

/** Normalised, renderable analysis. Mirrors the Dart `ChartAnalysis` model exactly. */
export interface ChartAnalysis {
  bias: Bias;
  levels: number[];
  entry: number | null;
  sl: number | null;
  tp: number[];
  note: string;
}

/** A chart path is `<user_id>/<file>` ΓÇö first folder must be the caller, nothing else. */
export function isOwnImagePath(path: unknown, callerId: string): path is string {
  if (typeof path !== 'string') return false;
  if (path.length === 0 || path.length > 512) return false;
  // No traversal, no absolute URLs: a plain relative path under exactly one folder.
  if (path.startsWith('/') || path.includes('..') || path.includes('://')) return false;
  const [folder, ...rest] = path.split('/');
  if (rest.length === 0) return false; // must live INSIDE the caller's folder
  return folder === callerId;
}

/** MIME by extension. The client uploads png/jpg; anything else is refused before download. */
export function mimeForPath(path: string): string | null {
  const lower = path.toLowerCase();
  if (lower.endsWith('.png')) return 'image/png';
  if (lower.endsWith('.jpg') || lower.endsWith('.jpeg')) return 'image/jpeg';
  if (lower.endsWith('.webp')) return 'image/webp';
  return null;
}

/**
 * The prompt. Deterministic: same contract every time, so two analyses of one screenshot are
 * comparable and the wording can be reviewed in source (TRD ┬º7).
 *
 * The system prompt carries the compliance framing the AGENTS guardrails require ΓÇö descriptive
 * only, no entry instruction, no profit claim, no forecast ΓÇö because the output is a plan a
 * trader will act on. Levels must be READ from the visible price axis, never invented: the
 * model has no market data beyond the pixels it was given.
 */
export function buildPrompt(): { system: string; user: string } {
  return {
    system: [
      'You analyze ONE trading chart screenshot for a retail forex/gold journal app.',
      'You are an educator describing what the image shows, not a broker, advisor or signal provider.',
      'Rules you must follow:',
      '- Describe only what is visible in the image. You have no market data beyond these pixels.',
      '- Read price levels from the visible price axis. Never invent or estimate a price you cannot see.',
      '- Never promise or imply profit, a win rate, or a future outcome.',
      '- Never tell the viewer to open, add to, or close a position now.',
      '- If the image is not a trading chart, or prices are unreadable, say so in "note" and return neutral bias with empty levels.',
      '- Return JSON only, matching the requested schema, with no prose outside it.',
    ].join('\n'),
    user: [
      'Analyze this chart. Respond with JSON only using exactly these keys:',
      '{"bias": "bullish" | "bearish" | "neutral",',
      ' "levels": number[] (up to 6 visible support/resistance prices, nearest first),',
      ' "entry": number | null (only if the image marks a clear entry zone),',
      ' "sl": number | null (only if the image marks a stop),',
      ' "tp": number[] (up to 3 visible targets),',
      ' "note": string (<= 300 chars: what the image shows and any legibility caveat)}',
    ].join('\n'),
  };
}

/**
 * Pulls the JSON object out of a model reply. Mirrors `ai-review`'s parser: strip a ```json
 * fence, take the outermost braces, refuse arrays and anything unparseable.
 */
export function parseModelJson(text: string | null | undefined): unknown {
  if (typeof text !== 'string') return null;
  const trimmed = text.trim();
  if (trimmed.length === 0) return null;

  const unfenced = trimmed
    .replace(/^```(?:json)?\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim();
  if (unfenced.startsWith('[')) return null;

  const start = unfenced.indexOf('{');
  const end = unfenced.lastIndexOf('}');
  if (start === -1 || end <= start) return null;

  try {
    const parsed: unknown = JSON.parse(unfenced.slice(start, end + 1));
    return typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)
      ? parsed
      : null;
  } catch {
    return null;
  }
}

/**
 * Turns whatever the model returned into an analysis that is safe to render.
 *
 * Returns null when there is nothing usable at all ΓÇö no bias AND no numbers ΓÇö that is a failed
 * call, and the caller must not persist or render an empty analysis as though the model had
 * read the chart. Every other field degrades to a safe value: unknown bias ΓåÆ neutral, missing
 * entry/sl ΓåÆ null, junk in the lists ΓåÆ dropped.
 */
export function normaliseAnalysis(raw: unknown): ChartAnalysis | null {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) return null;
  const record = raw as Record<string, unknown>;

  const bias = normaliseBias(record.bias);
  const levels = numberList(record.levels, MAX_LEVELS);
  const entry = finiteOrNull(record.entry);
  const sl = finiteOrNull(record.sl);
  const tp = numberList(record.tp, MAX_TAKE_PROFITS);
  const note = clip(str(record.note), MAX_NOTE_CHARS);

  const hasAnything = levels.length > 0 || entry !== null || sl !== null || tp.length > 0 ||
    note.length > 0;
  if (!hasAnything && bias === 'neutral') return null;

  return { bias, levels, entry, sl, tp, note };
}

/** Anything that is not exactly 'bullish'/'bearish' is neutral ΓÇö a hallucinated bias must not
 * render as conviction. */
export function normaliseBias(value: unknown): Bias {
  return value === 'bullish' || value === 'bearish' ? value : 'neutral';
}

/** Finite numbers only, capped in count. Non-numbers and NaN/Infinity are dropped. */
function numberList(value: unknown, max: number): number[] {
  if (!Array.isArray(value)) return [] as number[];
  const out: number[] = [];
  for (const entry of value) {
    const n = finiteOrNull(entry);
    if (n === null) continue;
    out.push(n);
    if (out.length >= max) break;
  }
  return out;
}

function finiteOrNull(value: unknown): number | null {
  const n =
    typeof value === 'number'
      ? value
      : typeof value === 'string' && value.trim() !== ''
        ? Number(value)
        : NaN;
  return Number.isFinite(n) ? n : null;
}

function clip(value: string, max: number): string {
  return value.replace(/\s+/g, ' ').trim().slice(0, max);
}

function str(value: unknown): string {
  return typeof value === 'string' ? value : '';
}
